#!/usr/bin/env bash
#
# PreToolUse hook (Edit/Write/MultiEdit/NotebookEdit): blocks hand edits to
# generated output and to the archival question-bank copy. Exit code 2 blocks
# the tool call and shows stderr to the agent.
#
# Set PM_ALLOW_GENERATED_EDITS=1 in the environment to bypass it on purpose.

set -uo pipefail

[[ "${PM_ALLOW_GENERATED_EDITS:-}" == "1" ]] && exit 0

input="$(cat)"
if command -v jq >/dev/null 2>&1; then
  file="$(printf '%s' "$input" | jq -r '.tool_input.file_path // .tool_input.notebook_path // empty')"
else
  file="$(printf '%s' "$input" | python3 -c 'import json,sys; t=json.load(sys.stdin).get("tool_input",{}); print(t.get("file_path") or t.get("notebook_path") or "")')"
fi
[[ -n "$file" ]] || exit 0

block() {
  echo "Blocked: $file is $1" >&2
  echo "Edit the source instead, then run: fvm exec ./tool/regen.sh  (see CLAUDE.md, 'Never edit by hand')." >&2
  exit 2
}

case "$file" in
  *.g.dart)
    block "generated by build_runner (source: the sibling .dart file)." ;;
  */packages/pm_questions_bank/assets/pm_260326_json/*)
    block "compiled question JSON (source: packages/pm_questions_bank/assets/pm_260326/*.txt)." ;;
  */pm_app/lib/l10n/app_localizations*.dart)
    block "generated localizations (source: pm_app/lib/l10n/app_es.arb)." ;;
esac

# Archival upstream copy at the repository root (not the package assets copy).
if [[ "$file" == */pm_260326/* && "$file" != */assets/pm_260326/* ]]; then
  root_candidate="${file%%/pm_260326/*}"
  if [[ -f "$root_candidate/.fvmrc" ]]; then
    echo "Blocked: $file is in the archival upstream copy, which nothing reads." >&2
    echo "Fix questions in packages/pm_questions_bank/assets/pm_260326/ and recompile." >&2
    exit 2
  fi
fi

exit 0
